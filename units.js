class Unit {
  constructor(name, factor, offset) {
    this.name = name;
    this.symbol = name.split(" — ")[0];
    this.factor = factor;
    this.offset = offset || 0;
  }
  toBase(v) { return v * this.factor + this.offset; }
  fromBase(b) { return (b - this.offset) / this.factor; }
}

class Category {
  constructor(name) {
    this.name = name;
    this.units = [];
    this.defaultFrom = 0;
    this.defaultTo = 1;
    this.minBase = -Infinity;
    this.minMessage = null;
    this.note = null;
  }
  u(name, factor, offset) { this.units.push(new Unit(name, factor, offset)); return this; }
  def(from, to) { this.defaultFrom = from; this.defaultTo = to; return this; }
  indexOf(symbol) { return this.units.findIndex(u => u.symbol === symbol); }
}

