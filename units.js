// ---------- числа: ввод с запятой или точкой, вывод по-русски ----------

const NBSP = " ";
const NUM_RX = /^[+-]?(\d+\.?\d*|\.\d+)(e[+-]?\d+)?$/i;

function parseNum(s) {
  s = String(s == null ? "" : s).trim().replace(/[\s  ]/g, "").replace(/,/g, ".").replace(/−/g, "-");
  if (!NUM_RX.test(s)) return null;
  const v = Number(s);
  return isFinite(v) ? v : null;
}

// Округление по десятичной записи (2,345 → 2,35), как в Windows-версии.
// dec — число знаков после запятой, может быть отрицательным (округление до десятков и т. п.)
function roundDec(v, dec) {
  if (!isFinite(v) || v === 0) return v;
  const sign = v < 0 ? -1 : 1;
  const parts = Math.abs(v).toPrecision(15).split("e");
  const exp = parts[1] ? Number(parts[1]) : 0;
  if (exp + dec > 19) return v;   // точности double уже не хватает — округлять нечего
  const shifted = Math.round(Number(parts[0] + "e" + (exp + dec)));
  return sign * Number(shifted + "e" + (-dec));
}

function groupDigits(intPart, group) {
  return group ? intPart.replace(/\B(?=(\d{3})+(?!\d))/g, NBSP) : intPart;
}

function fixedString(r, dec, group, trimZeros) {
  let s = Math.abs(r).toFixed(Math.max(0, Math.min(dec, 20)));
  let [ip, fp] = s.split(".");
  if (fp && trimZeros) fp = fp.replace(/0+$/, "");
  let out = groupDigits(ip, group) + (fp ? "," + fp : "");
  if (r < 0 && /[1-9]/.test(out)) out = "-" + out;
  return out;
}

function expString(v, digits) {
  let [m, e] = v.toExponential(Math.max(digits - 1, 1)).split("e");
  if (m.includes(".")) m = m.replace(/0+$/, "").replace(/\.$/, "");
  return m.replace(".", ",") + "E" + (e[0] === "-" ? e : "+" + e.replace("+", ""));
}

// digits значащих цифр; маленькие и огромные числа — в виде 1,5E+20
function fmt(v, digits, group) {
  if (v == null || !isFinite(v)) return "—";
  if (v === 0) return "0";
  const a = Math.abs(v);
  if (a >= 1e-6 && a < 1e15) {
    const mag = Math.floor(Math.log10(a));
    const dec = digits - 1 - mag;
    const r = roundDec(v, dec);
    return fixedString(r, dec, group, true);
  }
  return expString(v, digits);
}

// ровно dec знаков после запятой (для калькулятора)
function fmtFixed(v, dec, group) {
  if (v == null || !isFinite(v)) return "—";
  if (Math.abs(v) >= 1e15) return fmt(v, 12, group);
  return fixedString(roundDec(v, dec), dec, group, false);
}
